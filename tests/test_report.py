"""Unit tests for backend/report.py (REQUIREMENTS.md section 8): pure HTML
rendering from an engine summary + raw rows, no network, no Firestore.
"""
from engine.earnings import compute_trip_summary, compute_weekly_summary
from engine.models import CostInputs, PayoutLine, TripInput, WeekInput

from backend.report import render_trip_report, render_weekly_report


def _worked_example_trip_html():
    # REQUIREMENTS.md section 5.1 worked example.
    trips = [
        TripInput(base_pay=80.0, incentive=20.0, tip=10.0, deductions=[10.0], total_payout=100.0, distance_km=5.0, duration_min=25.0),
        TripInput(base_pay=60.0, distance_km=3.0, duration_min=15.0),
    ]
    summary = compute_trip_summary(trips, CostInputs(fuel_cost_per_km=3.0, maintenance_cost_per_km=1.0), logged_in_hours=1.5)
    trip_rows = [
        {"deductions": [{"label": "Platform fee", "amount": 10.0}]},
        {"deductions": []},
    ]
    return render_trip_report(summary, trip_rows)


def test_trip_report_escapes_a_malicious_deduction_label():
    trip_rows = [
        {"base_pay": 100.0, "incentive": 0.0, "tip": 0.0, "distance_km": 5.0, "duration_min": 20.0,
         "total_payout": 90.0, "deductions": [{"label": "<script>alert(1)</script>", "amount": 10.0}]},
    ]
    trips = [TripInput(base_pay=100.0, incentive=0.0, tip=0.0, total_payout=90.0, distance_km=5.0, duration_min=20.0, deductions=[10.0])]
    summary = compute_trip_summary(trips, CostInputs(fuel_cost_per_km=0.0, maintenance_cost_per_km=0.0))

    html = render_trip_report(summary, trip_rows)

    assert "<script>alert(1)</script>" not in html
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in html


def test_trip_report_declares_utf8_and_has_no_dollar_sign():
    html = _worked_example_trip_html()
    assert '<meta charset="utf-8">' in html
    assert "$" not in html


def test_trip_report_every_money_figure_has_the_rupee_symbol():
    html = _worked_example_trip_html()
    for expected in ("₹170.00", "₹10.00", "₹160.00", "₹32.00", "₹128.00"):
        assert expected in html, f"missing {expected!r}"


def test_trip_report_worked_example_exact_figures():
    # REQUIREMENTS.md section 5.1 worked example: gross 170, deductions 10,
    # net payout 160, costs 32, net earnings 128, 192.00/hr on trips,
    # 85.33/hr online, 20.00/km, deduction share 5.9%.
    html = _worked_example_trip_html()
    assert "₹170.00" in html  # gross pay
    assert "₹10.00" in html  # platform deductions
    assert "₹160.00" in html  # net payout
    assert "₹32.00" in html  # worker costs
    assert "₹128.00" in html  # net earnings
    assert "₹192.00 per hour on trips" in html
    assert "₹85.33 per hour online" in html
    assert "₹20.00 per km" in html
    assert "5.9%" in html


def test_trip_report_uses_the_same_labels_as_the_qa_glossary():
    from backend.qa import GLOSSARY
    html = _worked_example_trip_html()
    for field in ("gross_pay", "platform_deductions", "net_payout", "worker_costs", "net_earnings",
                  "net_per_engaged_hour", "net_per_logged_in_hour", "net_payout_per_km", "deduction_share"):
        label = GLOSSARY[field]
        capitalized = label[0].upper() + label[1:]
        assert capitalized in html, f"missing glossary label {capitalized!r} for {field}"


