"""Change-detection evaluation on simulated trip histories (REQUIREMENTS.md section 13).

No Gemini calls. Reads the 20 histories generated by eval/generate_data.py
(run with --histories first if eval/histories/ is empty), runs detect_change()
on each, and reports precision, recall and false-alarm rate.

Usage (PowerShell):
    python -m eval.generate_data --histories   # generates eval/histories/ if missing
    python -m eval.run_change_eval
"""
import json
from pathlib import Path

from engine.changes import detect_change
from engine.models import TripInput

ROOT = Path(__file__).resolve().parent.parent
HISTORIES_DIR = ROOT / "eval" / "histories"
RESULTS_FILE = ROOT / "eval" / "RESULTS.md"


def _load_trip_inputs(trips: list) -> list:
    return [
        TripInput(
            base_pay=t.get("base_pay"),
            incentive=t.get("incentive"),
            tip=t.get("tip"),
            deductions=[d["amount"] for d in t.get("deductions", [])],
            total_payout=t.get("total_payout"),
            distance_km=t.get("distance_km"),
            duration_min=t.get("duration_min"),
            trip_date=t.get("trip_date"),
            date_confirmed=bool(t.get("date_confirmed", False)),
        )
        for t in trips
    ]


def run_eval() -> dict:
    index_path = HISTORIES_DIR / "index.json"
    if not index_path.exists():
        raise FileNotFoundError(
            f"{index_path} not found. Run:\n"
            "    python -m eval.generate_data --histories"
        )

    index = json.loads(index_path.read_text())
    results = []
    for entry in index:
        history_path = ROOT / entry["path"]
        history = json.loads(history_path.read_text())
        split_date = history["split_date"]
        all_trips = _load_trip_inputs(history["trips"])
        baseline = [t for t in all_trips if t.trip_date and t.trip_date < split_date]
        recent = [t for t in all_trips if t.trip_date and t.trip_date >= split_date]
        result = detect_change(baseline, recent)
        results.append({
            "history_id": history["history_id"],
            "injected_cut": history["injected_cut"],
            "status": result.status,
            "relative_change": result.relative_change,
            "baseline_count": result.baseline_count,
            "recent_count": result.recent_count,
        })

    # Confusion matrix
    # "positive" = injected pay cut; "predicted positive" = status == "possible_change"
    tp = sum(1 for r in results if r["injected_cut"] and r["status"] == "possible_change")
    fp = sum(1 for r in results if not r["injected_cut"] and r["status"] == "possible_change")
    fn = sum(1 for r in results if r["injected_cut"] and r["status"] != "possible_change")
    tn = sum(1 for r in results if not r["injected_cut"] and r["status"] != "possible_change")
    insufficient = sum(1 for r in results if r["status"] == "insufficient_data")

    n_positive = sum(1 for r in results if r["injected_cut"])
    n_negative = sum(1 for r in results if not r["injected_cut"])

    precision = tp / (tp + fp) if (tp + fp) > 0 else None
    recall = tp / n_positive if n_positive > 0 else None
    false_alarm_rate = fp / n_negative if n_negative > 0 else None

    return {
        "n_histories": len(results),
        "n_with_cut": n_positive,
        "n_stable": n_negative,
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
        "insufficient_data_count": insufficient,
        "precision": precision,
        "recall": recall,
        "false_alarm_rate": false_alarm_rate,
        "detail": results,
    }


def _fmt(val, decimals=3):
    if val is None:
        return "N/A"
    return f"{val:.{decimals}f}"


def print_report(r: dict):
    print(f"\n=== Change-detection evaluation ({r['n_histories']} histories) ===")
    print(f"  Injected pay-cut: {r['n_with_cut']} histories")
    print(f"  Stable:           {r['n_stable']} histories")
    print()
    print(f"  True positives (correctly flagged):     {r['tp']}")
    print(f"  False positives (wrongly flagged):      {r['fp']}")
    print(f"  False negatives (cut missed):           {r['fn']}")
    print(f"  True negatives (correctly not flagged): {r['tn']}")
    print(f"  Insufficient data (status):             {r['insufficient_data_count']}")
    print()
    print(f"  Precision:        {_fmt(r['precision'])}")
    print(f"  Recall:           {_fmt(r['recall'])}")
    print(f"  False-alarm rate: {_fmt(r['false_alarm_rate'])}")
    print()
    print("  Per-history results:")
    for d in r["detail"]:
        label = "cut" if d["injected_cut"] else "stable"
        print(f"    {d['history_id']} ({label}): status={d['status']} "
              f"Δ={_fmt(d['relative_change'], 4) if d['relative_change'] is not None else 'N/A'} "
              f"baseline_n={d['baseline_count']} recent_n={d['recent_count']}")


def append_to_results_md(r: dict):
    section = f"""
## Change-detection evaluation ({r['n_histories']} simulated trip histories)

Generated by `eval/run_change_eval.py` on {__import__('datetime').date.today().isoformat()}.
No Gemini calls. Histories generated by `eval/generate_data.py --histories`.
Half the histories have a 10% per-km pay cut injected at the period boundary.

| Metric | Value |
|---|---|
| Histories total | {r['n_histories']} |
| With injected cut | {r['n_with_cut']} |
| Stable | {r['n_stable']} |
| True positives | {r['tp']} |
| False positives | {r['fp']} |
| False negatives | {r['fn']} |
| True negatives | {r['tn']} |
| Insufficient-data | {r['insufficient_data_count']} |
| **Precision** | **{_fmt(r['precision'])}** |
| **Recall** | **{_fmt(r['recall'])}** |
| **False-alarm rate** | **{_fmt(r['false_alarm_rate'])}** |

Notes: precision and recall are computed over histories where detect_change() returned
a conclusive result (possible_change or no_clear_change). Histories with insufficient_data
count as missed detections (false negatives) for recall. The 10% cut is well above the
5% threshold, so the signal should be detectable at 20 trips per period.
"""
    with open(RESULTS_FILE, "a", encoding="utf-8") as f:
        f.write(section)
    print(f"\nAppended results to {RESULTS_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    r = run_eval()
    print_report(r)
    append_to_results_md(r)
